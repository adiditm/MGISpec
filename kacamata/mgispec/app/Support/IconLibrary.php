    /** Flat list for the picker: name, class, label, search text and group. */
    public static function all(): array
    {
        $icons = [];

        foreach (self::GROUPS as $group => $items) {
            foreach ($items as $name => $meta) {
                if (isset($icons[$name])) {
                    continue;
                }
                [$label, $words] = array_pad(explode('|', $meta, 2), 2, '');
                $icons[$name] = [
                    'class' => 'fa-solid fa-'.$name,
                    'label' => $label,
                    'search' => mb_strtolower("$label $words $name"),
                    'group' => $group,
                ];
            }
        }

        return array_values($icons);
    }

    public static function groups(): array
    {
        return array_keys(self::GROUPS);
    }
