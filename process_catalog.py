def save_square_webp(src_path: Path, dest_path: Path, size=1200, quality=88):
    dest_path.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(src_path) as im:
        if im.mode in ('RGBA', 'LA'):
            bg = Image.new('RGB', im.size, (255, 255, 255))
            bg.paste(im, mask=im.split()[-1])
            im = bg
        else:
            im = im.convert('RGB')
        
        # Check aspect ratio
        w, h = im.size
        if w == h:
            resized = im.resize((size, size), Image.Resampling.LANCZOS)
        else:
            # Fit inside size x size, paste on white canvas
            ratio = min(size / w, size / h)
            nw, nh = int(w * ratio), int(h * ratio)
            resized_sub = im.resize((nw, nh), Image.Resampling.LANCZOS)
            resized = Image.new('RGB', (size, size), (255, 255, 255))
            resized.paste(resized_sub, ((size - nw) // 2, (size - nh) // 2))
        
        resized.save(dest_path, 'WEBP', quality=quality, method=6)

def select_images_for_folder(folder_path: Path):
    all_files = sorted([f for f in folder_path.iterdir() if f.suffix.lower() in ('.png', '.jpg', '.jpeg') and not f.name.startswith('.')])
    
    # Priority for hero / thumbnail:
    # 1. Named files like 'KID13 - Pink.png', 'TT22 - Black.png', 'SG013 - LEOPARD PRINT.png'
    # 2. '01_glossy_angle.png'
    # 3. If none, pick _MG_xxxx[0] (or [1]) avoiding temple macros like '016f...'
    
    named_heroes = [f for f in all_files if not f.name.startswith('_MG_') and not f.name.startswith('016f') and not f.name.startswith('0')]
    glossy_heroes = [f for f in all_files if f.name.startswith('01_glossy')]
    
    hero = None
    if named_heroes:
        hero = named_heroes[0]
    elif glossy_heroes:
        hero = glossy_heroes[0]
    else:
        # Filter out 016f if present
        valid_mgs = [f for f in all_files if not f.name.startswith('016f')]
        if valid_mgs:
            hero = valid_mgs[0]
    
    # Select gallery files
    # If folder has glossy named files (02_... to 09_...), use them
    glossy_gallery = [f for f in all_files if f.name.startswith('0') and f != hero and 'detail' in f.name or 'view' in f.name or 'quarter' in f.name]
    
    gallery = []
    if glossy_gallery:
        gallery = glossy_gallery
    else:
        # Pick from all files excluding hero and 016f
        remaining = [f for f in all_files if f != hero and not f.name.startswith('016f')]
        # Pick up to 8 diverse angles
        gallery = remaining[:8]
    
    return hero, gallery

def main():
    print(f"Starting processing for {len(PRODUCTS_METADATA)} products...")
    
    STORAGE_APP_PRODUCTS.mkdir(parents=True, exist_ok=True)
    PUBLIC_STORAGE_PRODUCTS.mkdir(parents=True, exist_ok=True)
    
    processed_products = []
    
    for idx, item in enumerate(PRODUCTS_METADATA, 1):
        src_parent = P1_DIR if item['p_dir'] == 1 else P2_DIR
        folder_path = src_parent / item['folder']
        
        if not folder_path.exists():
            print(f"ERROR: Folder {folder_path} does not exist!")
            continue
            
        hero_file, gallery_files = select_images_for_folder(folder_path)
        slug = item['slug']
        
        # Paths in storage
        app_prod_dir = STORAGE_APP_PRODUCTS / slug
        pub_prod_dir = PUBLIC_STORAGE_PRODUCTS / slug
        app_prod_dir.mkdir(parents=True, exist_ok=True)
        pub_prod_dir.mkdir(parents=True, exist_ok=True)
        
        # 1. Process thumbnail
        thumb_filename = "thumbnail.webp"
        app_thumb_path = app_prod_dir / thumb_filename
        save_square_webp(hero_file, app_thumb_path)
        shutil.copy2(app_thumb_path, pub_prod_dir / thumb_filename)
        
        # 2. Process gallery
        gallery_rel_paths = []
        for g_idx, g_file in enumerate(gallery_files, 1):
            g_filename = f"gallery-{g_idx:02d}.webp"
            app_g_path = app_prod_dir / g_filename
            save_square_webp(g_file, app_g_path)
            shutil.copy2(app_g_path, pub_prod_dir / g_filename)
            gallery_rel_paths.append(f"products/{slug}/{g_filename}")
        
        product_record = {
            **item,
            'sort_order': idx,
            'thumbnail': f"products/{slug}/thumbnail.webp",
            'gallery': gallery_rel_paths,
        }
        processed_products.append(product_record)
        print(f"[{idx}/46] {item['name_en']}: thumb + {len(gallery_rel_paths)} gallery images OK")

    # Save JSON manifest
    manifest_path = BASE_DIR / 'kacamata/mgispec/database/seeders/products_catalog_data.json'
    with open(manifest_path, 'w', encoding='utf-8') as f:
        json.dump(processed_products, f, indent=2, ensure_ascii=False)
    print(f"\nSaved products catalog manifest to {manifest_path}")

if __name__ == '__main__':
    main()
